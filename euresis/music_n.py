"""Music theory across tuning systems: theorems about scales in every N-note equal temperament,
proved by exhaustion.

Western music uses 12 equal steps per octave, but 5-, 7-, 10-, 15-, 16-, 19-, 22-, 31-TET… are
used too and much less studied. Here Euresis takes every equal temperament with
N_MIN ≤ N ≤ N_MAX steps, enumerates every scale (every subset of the N steps) up to
transposition and inversion, and evaluates scale properties that make sense in any
tuning: maximal evenness, Myhill's property, deep scales, generated scales, Rothenberg
propriety (strict and non-strict), symmetry, Z-relation, complement relations, and
step patterns.

It looks for statements "in every N-TET in the range, every scale with property A has
property B" (or A ⇔ B), across all scale sizes. Each statement is **proved** for every
tuning in the range by checking every scale; the verification gate (claim kind ``music``
with a list of universes) re-checks all of them independently, without using set
classes. Beyond the range it is a conjecture, and is labelled so.
"""
from __future__ import annotations

import itertools
import json
import math
import time
from functools import lru_cache

from .registry import ROOT, Registry, atomic_write

N_MIN, N_MAX = 5, 16
STATE = ROOT / "space" / "music_n_state.json"
LOG = ROOT / "space" / "music_n_log.md"


def pcs(m, N):
    return [i for i in range(N) if m >> i & 1]


def rot(m, t, N):
    t %= N
    full = (1 << N) - 1
    return ((m << t) | (m >> (N - t))) & full if t else m


def inv(m, N):
    return sum(1 << ((-i) % N) for i in pcs(m, N))


def canon(m, N):
    return min(min(rot(m, t, N), rot(inv(m, N), t, N)) for t in range(N))


def iv(m, N):
    p = pcs(m, N)
    v = [0] * (N // 2)
    for a, b in itertools.combinations(p, 2):
        d = (b - a) % N
        v[min(d, N - d) - 1] += 1
    return tuple(v)


def spans(m, N):
    p = pcs(m, N)
    k = len(p)
    return {d: {(p[(i + d) % k] - p[i]) % N for i in range(k)} for d in range(1, k)}


# ---------------------------------------------------------------- properties (any N)
def maximally_even(m, N, _ctx=None):
    k = bin(m).count("1")
    return 2 <= k < N and all(v <= {(N * d) // k, -(-N * d // k)} for d, v in spans(m, N).items())


def myhill(m, N, _ctx=None):
    k = bin(m).count("1")
    return 2 <= k < N and all(len(v) == 2 for v in spans(m, N).values())


def deep(m, N, _ctx=None):
    v = iv(m, N)
    k = bin(m).count("1")
    return 2 <= k < N and len(set(v)) == len(v)


def generated(m, N, _ctx=None):
    k = bin(m).count("1")
    if not 2 <= k < N:
        return False
    for g in range(1, N):
        s = sum(1 << (j * g % N) for j in range(k))
        if bin(s).count("1") == k and any(rot(s, t, N) == m for t in range(N)):
            return True
    return False


def proper(m, N, _ctx=None):
    sp = spans(m, N)
    k = bin(m).count("1")
    return 2 <= k < N and all(max(sp[d]) <= min(sp[d + 1]) for d in range(1, k - 1))


def strictly_proper(m, N, _ctx=None):
    sp = spans(m, N)
    k = bin(m).count("1")
    return 2 <= k < N and all(max(sp[d]) < min(sp[d + 1]) for d in range(1, k - 1))


def t_sym(m, N, _ctx=None):
    return any(rot(m, t, N) == m for t in range(1, N))


def i_sym(m, N, _ctx=None):
    im = inv(m, N)
    return any(rot(im, t, N) == m for t in range(N))


def same_iv_as_complement(m, N, _ctx=None):
    return iv(m, N) == iv(~m & ((1 << N) - 1), N)


def z_related(m, N, ctx=None):
    return (ctx or zgroups(N)).get((bin(m).count("1"), iv(m, N)), 1) > 1


def no_unit_step(m, N, _ctx=None):
    return iv(m, N)[0] == 0


def no_two_unit_steps_in_a_row(m, N, _ctx=None):
    return not any(m >> i & 1 and m >> ((i + 1) % N) & 1 and m >> ((i + 2) % N) & 1 for i in range(N))


def two_step_sizes(m, N, _ctx=None):
    """its adjacent steps take exactly two sizes"""
    sp = spans(m, N)
    return 1 in sp and len(sp[1]) == 2


PROPS = {
    "is maximally even": maximally_even,
    "has Myhill's property": myhill,
    "is a deep scale": deep,
    "is generated by a single interval": generated,
    "is proper (Rothenberg)": proper,
    "is strictly proper (Rothenberg)": strictly_proper,
    "is transpositionally symmetric": t_sym,
    "is inversionally symmetric": i_sym,
    "has the same interval vector as its complement": same_iv_as_complement,
    "is Z-related to another scale": z_related,
    "has no single-step interval": no_unit_step,
    "has no two single steps in a row": no_two_unit_steps_in_a_row,
    "has exactly two step sizes": two_step_sizes,
}

DEFINITIONAL = {("has no single-step interval", "has no two single steps in a row"),
                ("is strictly proper (Rothenberg)", "is proper (Rothenberg)"),
                ("has Myhill's property", "has exactly two step sizes")}
DIATONIC_THEORY = {"is maximally even", "has Myhill's property", "is a deep scale", "is generated by a single interval",
                   "is proper (Rothenberg)", "is strictly proper (Rothenberg)", "has exactly two step sizes"}
KNOWN = {
    ("is generated by a single interval", "is inversionally symmetric"):
        "elementary: {0, g, …, (k−1)g} is symmetric under j ↦ k−1−j",
    ("has Myhill's property", "is generated by a single interval"): "well-formed scales (Carey & Clampitt 1989)",
    ("is maximally even", "is inversionally symmetric"): "maximally even sets (Clough & Douthett 1991)",
    ("is maximally even", "is proper (Rothenberg)"): "maximally even sets are proper (Clough & Douthett 1991)",
}


@lru_cache(maxsize=None)
def classes(N):
    """one representative per scale class (transposition + inversion), every size 1..N-1"""
    seen = set()
    for m in range(1, (1 << N) - 1):
        c = canon(m, N)
        seen.add(c)
    return tuple(sorted(seen))


@lru_cache(maxsize=None)
def zgroups(N):
    g = {}
    for c in classes(N):
        key = (bin(c).count("1"), iv(c, N))
        g[key] = g.get(key, 0) + 1
    return g


@lru_cache(maxsize=None)
def table(N):
    ctx = zgroups(N)
    return {name: frozenset(c for c in classes(N) if f(c, N, ctx)) for name, f in PROPS.items()}


# ---------------------------------------------------------------- verifier
@lru_cache(maxsize=None)
def full_table(N):
    """Independent of set classes: evaluate every property on EVERY subset of the N steps."""
    ctx = zgroups(N)
    return {name: frozenset(m for m in range(1, (1 << N) - 1) if f(m, N, ctx)) for name, f in PROPS.items()}


def verify_claim(p: dict) -> tuple[str, dict]:
    """Every scale (every subset, not just class representatives) in every listed N-TET."""
    checked = 0
    for N in p["universes"]:
        T = full_table(N)
        A = frozenset.intersection(*[T[x] for x in p["premise"]]) if p["premise"] else frozenset(range(1, (1 << N) - 1))
        B = T[p["conclusion"]]
        checked += (1 << N) - 2
        bad = (A - B) | ((B - A) if p.get("equivalence") else frozenset())
        if bad:
            m = min(bad)
            return "refuted", {"counterexample": {"N": N, "scale": pcs(m, N)}, "checked": checked}
    return "proved", {"method": f"exhaustive: every scale in every N-TET for N in {p['universes'][0]}..{p['universes'][-1]}",
                      "scales_checked": checked,
                      "note": "proved for these tunings only; beyond them it is a conjecture"}


# ---------------------------------------------------------------- discovery
def log(msg, echo=print):
    echo(msg)
    with LOG.open("a") as f:
        f.write(f"- {time.strftime('%Y-%m-%d %H:%M')} {msg}\n")


def run(reg: Registry | None = None, echo=print, n_max: int = N_MAX) -> dict:
    from . import gate
    reg = reg or Registry()
    st = json.loads(STATE.read_text()) if STATE.exists() else {"discoveries": [], "rediscoveries": [], "n_max_done": 0}
    Ns = list(range(N_MIN, n_max + 1))
    t0 = time.time()
    tabs = {}
    for N in Ns:
        tabs[N] = table(N)
        echo(f"  {N}-TET: {len(classes(N))} scale classes ({time.time() - t0:.0f} s)")
    holds = {}
    for a, b in itertools.permutations(PROPS, 2):
        if (a, b) in DEFINITIONAL:
            continue
        cells = [N for N in Ns if tabs[N][a]]
        if len(cells) < 4 or not all(tabs[N][a] <= tabs[N][b] for N in cells):
            continue
        support = sum(len(tabs[N][a]) for N in cells)
        if support < 15 or all(len(tabs[N][b]) == len(classes(N)) for N in cells):
            continue
        equiv = all(tabs[N][a] == tabs[N][b] for N in Ns)
        holds[(a, b)] = (equiv, support)
    for (a, b), (equiv, support) in sorted(holds.items(), key=lambda kv: -kv[1][1]):
        if equiv and (b, a) in holds and a > b:
            continue
        chain = next((h for h in PROPS if (a, h) in holds and (h, b) in holds), None)
        rel = "⇔" if equiv else "⇒"
        stmt = f"In every N-note equal temperament ({Ns[0]} ≤ N ≤ {Ns[-1]}): a scale {a}  {rel}  it {b}"
        payload = {"premise": [a], "conclusion": b, "universes": Ns, "equivalence": equiv}
        cid = reg.add("music", stmt, payload, source="music_n.py")
        if gate.check(reg, cid, log=lambda *x: None) != "proved":
            continue
        why = KNOWN.get((a, b)) or KNOWN.get((b, a))
        if why:
            reg.set_novelty(cid, f"known ({why})")
            st["rediscoveries"].append({"claim": cid, "statement": stmt, "known": why})
            echo(f"    rediscovered: {stmt}  ({why})")
        elif chain:
            reg.set_novelty(cid, f"follows from proved statements through '{chain}'")
        else:
            likely = a in DIATONIC_THEORY and b in DIATONIC_THEORY
            reg.set_novelty(cid, ("likely known or close to known results of diatonic set theory (Clough, Douthett, "
                                  "Carey, Clampitt, Rothenberg); " if likely else "") +
                            f"proved for {Ns[0]} ≤ N ≤ {Ns[-1]} only (a conjecture beyond); music-theory literature unchecked")
            rec = {"claim": cid, "statement": stmt, "support": support, "likely_known": likely}
            st["discoveries"].append(rec)
            log(f"{'CANDIDATE (likely known)' if likely else 'DISCOVERY'} (proved by exhaustion in {len(Ns)} tunings): "
                f"{stmt}  [{cid}; {support} scale classes]", echo)
    st["n_max_done"] = n_max
    atomic_write(STATE, json.dumps(st, indent=1) + "\n")
    return st
