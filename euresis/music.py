"""Music theory discovery: theorems about scales and chords, proved by exhaustion.

In 12-tone equal temperament every scale or chord is a pitch-class set, a subset of
{0, …, 11}. There are only 2¹² = 4096 of them, so a statement "every set of size n
with property A also has property B" can be **proved** by checking every set.

Euresis computes music-theoretic properties (interval vector, maximal evenness, Myhill's
property, deep scales, generated scales, symmetry, triads, complements, …), searches
for implications A ⇒ B and equivalences A ⇔ B within each cardinality, and sends each
candidate through the verification gate (claim kind ``music``), which re-checks all
4096 sets independently.

A *discovery* must be: proved by exhaustion · non-trivial (premise holds for at least
two scale types, conclusion is not true of every set of that size, and the conclusion
is not part of the premise) · not implied by a chain of earlier results · not one of
the classical theorems Euresis knows (those are reported as rediscoveries).
"""
from __future__ import annotations

import itertools
import json
import time
from functools import lru_cache

from .registry import ROOT, Registry

STATE = ROOT / "space" / "music_state.json"
LOG = ROOT / "space" / "music_log.md"
ALL = range(4096)


def pcs(mask: int) -> list[int]:
    return [i for i in range(12) if mask >> i & 1]


def transpose(mask: int, t: int) -> int:
    return ((mask << t) | (mask >> (12 - t))) & 0xFFF if t % 12 else mask


def invert(mask: int) -> int:
    return sum(1 << ((-i) % 12) for i in pcs(mask))


def complement(mask: int) -> int:
    return ~mask & 0xFFF


@lru_cache(maxsize=None)
def interval_vector(mask: int) -> tuple:
    p = pcs(mask)
    iv = [0] * 6
    for x, y in itertools.combinations(p, 2):
        d = (y - x) % 12
        iv[min(d, 12 - d) - 1] += 1
    return tuple(iv)


def _spans(mask: int):
    p = pcs(mask)
    n = len(p)
    return {d: {(p[(i + d) % n] - p[i]) % 12 for i in range(n)} for d in range(1, n)}


def contains(mask: int, chord: int) -> bool:
    return any(transpose(chord, t) & mask == transpose(chord, t) for t in range(12))


MAJOR, MINOR, DIM, AUG = 0b10010001, 0b10001001, 0b1001001, 0b100010001
TRITONE = 0b1000001


# ------------------------------------------------------------------- properties
def maximally_even(m):
    """Clough–Douthett: every generic interval d spans floor(12d/n) or ceil(12d/n) semitones."""
    n = bin(m).count("1")
    if n < 2:
        return False
    return all(v <= {(12 * d) // n, -(-12 * d // n)} for d, v in _spans(m).items())


def myhill(m):
    n = bin(m).count("1")
    return 2 <= n <= 11 and all(len(v) == 2 for v in _spans(m).values())


def deep(m):
    iv = interval_vector(m)
    return bin(m).count("1") >= 2 and len(set(iv)) == 6


def generated(m):
    n = bin(m).count("1")
    if n < 2:
        return False
    for g in range(1, 12):
        s = sum(1 << (k * g % 12) for k in range(n))
        if bin(s).count("1") == n and any(transpose(s, t) == m for t in range(12)):
            return True
    return False


def t_symmetric(m):
    return any(transpose(m, t) == m for t in range(1, 12))


def i_symmetric(m):
    inv = invert(m)
    return any(transpose(inv, t) == m for t in range(12))


def same_iv_as_complement(m):
    return interval_vector(m) == interval_vector(complement(m))


def z_related(m):
    """Another set with the same interval vector that is not a transposition or inversion of it."""
    iv = interval_vector(m)
    orbit = {transpose(x, t) for x in (m, invert(m)) for t in range(12)}
    return any(interval_vector(x) == iv and x not in orbit for x in _by_card(bin(m).count("1")))


@lru_cache(maxsize=None)
def _by_card(n):
    return tuple(x for x in ALL if bin(x).count("1") == n)


def no_semitone(m):
    return interval_vector(m)[0] == 0


def no_consecutive_semitones(m):
    return not any(m >> i & 1 and m >> ((i + 1) % 12) & 1 and m >> ((i + 2) % 12) & 1 for i in range(12))


PROPS = {
    "maximally even": maximally_even,
    "has Myhill's property (every generic interval comes in exactly two sizes)": myhill,
    "is a deep scale (all six interval-class counts differ)": deep,
    "is generated by a single interval": generated,
    "is transpositionally symmetric": t_symmetric,
    "is inversionally symmetric": i_symmetric,
    "has the same interval vector as its complement": same_iv_as_complement,
    "is Z-related to another set": z_related,
    "contains a major triad": lambda m: contains(m, MAJOR),
    "contains a minor triad": lambda m: contains(m, MINOR),
    "contains a diminished triad": lambda m: contains(m, DIM),
    "contains an augmented triad": lambda m: contains(m, AUG),
    "contains a tritone": lambda m: contains(m, TRITONE),
    "has no semitone": no_semitone,
    "has no two consecutive semitones": no_consecutive_semitones,
}

# classical results (rediscoveries, not discoveries)
KNOWN = {
    ("has the same interval vector as its complement", 6): "Babbitt's hexachord theorem",
    ("is a deep scale (all six interval-class counts differ)", "is generated by a single interval"):
        "deep scale theorem (Gamer 1967; Johnson): deep scales are generated",
    ("has Myhill's property (every generic interval comes in exactly two sizes)", "is generated by a single interval"):
        "Myhill's property ⇔ well-formed generated scale (Carey & Clampitt 1989)",
    ("maximally even", "is generated by a single interval"): "maximally even sets of coprime size are generated (Clough & Douthett 1991)",
    ("maximally even", "has Myhill's property (every generic interval comes in exactly two sizes)"):
        "maximally even sets have Myhill's property when size and 12 are coprime (Clough & Douthett 1991)",
}


# implications that hold by definition (the premise's chord contains the conclusion's interval, etc.)
DEFINITIONAL = {
    ("has no semitone", "has no two consecutive semitones"),
    ("contains a diminished triad", "contains a tritone"),
    ("is transpositionally symmetric", "is Z-related to another set"),
}
CHORDS = {"contains a major triad": MAJOR, "contains a minor triad": MINOR, "contains a diminished triad": DIM,
          "contains an augmented triad": AUG, "contains a tritone": TRITONE}
MIN_SUPPORT = 5            # premise must hold for at least this many set classes


def definitional(a, b) -> bool:
    if (a, b) in DEFINITIONAL:
        return True
    if a in CHORDS and b in CHORDS:                 # chord A contains chord/interval B
        return contains(CHORDS[a], CHORDS[b])
    return False


def truth_table(n: int) -> dict:
    sets = _by_card(n)
    return {name: frozenset(x for x in sets if f(x)) for name, f in PROPS.items()}


def scale_types(subset) -> int:
    """number of distinct set classes (up to transposition and inversion)"""
    seen = set()
    for x in subset:
        seen.add(min(transpose(y, t) for y in (x, invert(x)) for t in range(12)))
    return len(seen)


# ---------------------------------------------------------------- verifier (gate)
def verify_claim(p: dict) -> tuple[str, dict]:
    """Exhaustive check: for every pitch-class set of size n (or every size), premise ⇒ conclusion
    (or premise ⇔ conclusion)."""
    sizes = [p["cardinality"]] if p.get("cardinality") else list(range(1, 12))
    prem = [PROPS[x] for x in p["premise"]]
    concl = PROPS[p["conclusion"]]
    checked = 0
    for n in sizes:
        for m in _by_card(n):
            checked += 1
            a = all(f(m) for f in prem)
            b = concl(m)
            if (a and not b) or (p.get("equivalence") and b and not a):
                return "refuted", {"counterexample": pcs(m), "checked": checked}
    return "proved", {"method": "exhaustive enumeration of pitch-class sets", "sets_checked": checked}


# ----------------------------------------------------------------- discovery loop
def load_state():
    if STATE.exists():
        return json.loads(STATE.read_text())
    return {"discoveries": [], "rediscoveries": [], "edges": [], "done_cardinalities": []}


def save_state(st):
    STATE.write_text(json.dumps(st, indent=1) + "\n")


def log(msg, echo=print):
    echo(msg)
    with LOG.open("a") as f:
        f.write(f"- {time.strftime('%Y-%m-%d %H:%M')} {msg}\n")


def _known(a, b, n):
    for key, why in KNOWN.items():
        if key == (b, n) or key == (a, b) or key == (b, a):
            return why
    return None


def run(reg: Registry | None = None, echo=print) -> dict:
    from . import gate
    reg = reg or Registry()
    st = load_state()
    edges = {(e["a"], e["b"], e["n"]) for e in st["edges"]}
    for n in range(3, 10):
        if n in st["done_cardinalities"]:
            continue
        T = truth_table(n)
        total = len(_by_card(n))
        log(f"music: {n}-note sets ({total} sets, {scale_types(_by_card(n))} set classes)", echo)
        for b, Bs in T.items():                        # universal truths at this size
            if len(Bs) == total and b == "has the same interval vector as its complement":
                why = _known(None, b, n) or ""
                payload = {"premise": [], "conclusion": b, "cardinality": n}
                cid = reg.add("music", f"Every {n}-note pitch-class set {b}", payload, source="music.py")
                status = gate.check(reg, cid, log=lambda *x: None)
                if status == "proved":
                    reg.set_novelty(cid, f"known ({why})" if why else "not in Euresis' knowledge")
                    st["rediscoveries" if why else "discoveries"].append({"claim": cid, "statement": reg.get(cid)["statement"]})
                    echo(f"    {'rediscovered' if why else 'DISCOVERY'}: every {n}-note set {b}" + (f"  ({why})" if why else ""))
        for a, b in itertools.permutations(T, 2):
            As, Bs = T[a], T[b]
            if not As or len(Bs) == total or not As <= Bs or definitional(a, b):
                continue
            if scale_types(As) < MIN_SUPPORT and not _known(a, b, n):
                continue
            if As == Bs and a > b:                     # report each equivalence once
                continue
            if any((a, h, n) in edges and (h, b, n) in edges for h in T):
                continue                               # follows from a chain of earlier implications
            equiv = As == Bs
            payload = {"premise": [a], "conclusion": b, "cardinality": n, "equivalence": equiv}
            rel = "⇔" if equiv else "⇒"
            stmt = f"For {n}-note pitch-class sets: {a}  {rel}  {b}"
            cid = reg.add("music", stmt, payload, source="music.py")
            status = gate.check(reg, cid, log=lambda *x: None)
            if status != "proved":
                continue
            edges.add((a, b, n))
            st["edges"].append({"a": a, "b": b, "n": n})
            why = _known(a, b, n)
            if why:
                reg.set_novelty(cid, f"known ({why})")
                st["rediscoveries"].append({"claim": cid, "statement": stmt, "known": why})
                echo(f"    rediscovered: {stmt}  ({why})")
            else:
                reg.set_novelty(cid, "not among the classical theorems Euresis knows; music-theory literature "
                                     "unchecked (it may be known or follow directly from definitions)")
                rec = {"claim": cid, "statement": stmt, "support": scale_types(As)}
                st["discoveries"].append(rec)
                log(f"DISCOVERY (proved by exhaustion): {stmt}  [{cid}; {scale_types(As)} scale types]", echo)
        st["done_cardinalities"].append(n)
        save_state(st)
    if not st.get("general_done"):
        general(reg, st, echo)
        st["general_done"] = True
        save_state(st)
    return st


GENERAL_KNOWN = {("is generated by a single interval", "is inversionally symmetric"):
                 "elementary: a generated set {0, g, …, (n−1)g} is symmetric under k ↦ n−1−k"}


def general(reg, st, echo=print):
    """Implications that hold at EVERY size where the premise occurs: one theorem instead of many."""
    from . import gate
    tables = {n: truth_table(n) for n in range(2, 11)}
    proved = {(a, b) for a, b in itertools.permutations(PROPS, 2)
              if not definitional(a, b) and len([n for n in tables if tables[n][a]]) >= 3
              and all(tables[n][a] <= tables[n][b] for n in tables if tables[n][a])
              and not all(len(tables[n][b]) == len(_by_card(n)) for n in tables if tables[n][a])}
    proved_all = set(proved)
    proved = set()
    for a, b in sorted(itertools.permutations(PROPS, 2),
                       key=lambda ab: sum((ab[0], h) in proved_all and (h, ab[1]) in proved_all for h in PROPS)):
        if definitional(a, b):
            continue
        sizes = [n for n in tables if tables[n][a]]
        if len(sizes) < 3 or not all(tables[n][a] <= tables[n][b] for n in sizes):
            continue
        if all(len(tables[n][b]) == len(_by_card(n)) for n in sizes):
            continue
        payload = {"premise": [a], "conclusion": b, "cardinality": None}
        stmt = f"For pitch-class sets of every size: {a}  ⇒  {b}"
        cid = reg.add("music", stmt, payload, source="music.py")
        if gate.check(reg, cid, log=lambda *x: None) != "proved":
            continue
        why = GENERAL_KNOWN.get((a, b)) or _known(a, b, None)
        chain = next((h for h in PROPS if (a, h) in proved_all and (h, b) in proved_all), None)
        proved.add((a, b))
        if chain and not why:
            reg.set_novelty(cid, f"follows from proved implications through '{chain}'")
            continue
        if why:
            reg.set_novelty(cid, f"known ({why})")
            st["rediscoveries"].append({"claim": cid, "statement": stmt, "known": why})
            echo(f"    rediscovered (all sizes): {stmt}  ({why})")
        else:
            reg.set_novelty(cid, "not among the classical theorems Euresis knows; music-theory literature unchecked")
            st["discoveries"].append({"claim": cid, "statement": stmt, "support": "all sizes"})
            log(f"DISCOVERY (proved by exhaustion, all sizes): {stmt}  [{cid}]", echo)
